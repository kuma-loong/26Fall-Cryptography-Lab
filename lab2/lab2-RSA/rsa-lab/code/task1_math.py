# 【为什么要「负向」自检】
# 「跑通了几个例子」只证明你覆盖到的情形是对的。真正会咬人的是
# 「本该报错却悄悄返回了一个错值」—— 上面 modinv 的第 2 点就是典型。
# 所以下面既检查「该成功的成功」，也检查「该失败的失败」。


def _self_test() -> bool:
    section("任务一自检：扩展欧几里得 + 模逆")
    ok = True

    # 【注意这里没有 try/except 兜住「空没填」】
    # 空没填时 BlankNotFilled 会一路穿出 _self_test、穿出 main，
    # 最后被 fill.run() 接住，打印精确的文件与行号，并以退出码 3 结束。
    # 这正是我们要的：**「还没填」和「填错了」是两回事**，
    # 必须是两种不同的表现。用 except 抓它反而会把这两件事混起来。
    #
    # 顺带一提：这也演示了 BlankNotFilled 为什么必须继承 BaseException ——
    # 要是它继承 Exception，下面那些 `except ValueError` 旁边的
    # 宽 except 就会把它咽下去。

    # ---- 正向：Bézout 恒等式 ----
    print("【一】Bézout 恒等式  a·x + b·y = gcd(a, b)")
    cases = [(240, 46), (1071, 462), (3, 7), (1, 1), (0, 5), (7, 0), (17, 5)]
    bad = []
    for a, b in cases:
        g, x, y = egcd(a, b)
        if not (a * x + b * y == g == _math_gcd(a, b)):
            bad.append((a, b, g, x, y))
    if bad:
        ok = False
        print(f"  失败 {len(bad)}/{len(cases)} 例：")
        for a, b, g, x, y in bad[:3]:
            print(f"    egcd({a}, {b}) 给出 ({g}, {x}, {y})，"
                  f"但 a·x+b·y = {a * x + b * y}，而 gcd = {_math_gcd(a, b)}")
        print("  ⚠ 如果 g 和 gcd 对得上、但 a·x+b·y 不对，多半是")
        print("    把元组赋值拆成了两句顺序赋值（见填空 3、4 的说明）。")
    else:
        print(f"  全部 {len(cases)} 例通过")

    # ---- 正向：逆元确实能还原 ----
    # 最后一例是 1024 位的大数，用来确认你的实现在**真实规模**上也没问题
    # （小数字上对、大数字上错的情况是存在的，比如误用了浮点中间量）。
    print()
    print("【二】模逆  a · modinv(a, m) ≡ 1 (mod m)")
    inv_cases = [(3, 7), (17, 3120), (2, 5), (65537, 61 * 53), (65537, 2 ** 1024)]
    bad_inv = []
    for a, m in inv_cases:
        try:
            d = modinv(a, m)
        except ValueError as exc:
            bad_inv.append((a, m, f"不该报错却报了：{exc}"))
            continue
        if a * d % m != 1:
            bad_inv.append((a, m, f"a·d mod m = {a * d % m}，不是 1"))
    if bad_inv:
        ok = False
        print(f"  失败 {len(bad_inv)}/{len(inv_cases)} 例：")
        for a, m, why in bad_inv[:3]:
            print(f"    modinv({a}, {m})：{why}")
    else:
        print(f"  全部 {len(inv_cases)} 例通过")

    # ---- ⚠ 负向检查一：范围。这是唯一能抓住「负 d」的检查 ----
    print()
    print("【三】⚠ 返回值必须在 [0, m) 区间 —— 负 d 的唯一防线")
    try:
        d = modinv(3, 7)
    except ValueError as exc:
        print(f"  modinv(3, 7) 不该报错却报了：{exc}")
        ok = False
        d = None
    if d is not None:
        in_range = 0 <= d < 7
        print(f"  modinv(3, 7) = {d}   "
              f"{'通过（落在 [0, 7) 内）' if in_range else '✗ 失败'}")
        if not in_range:
            ok = False
            print("    ⚠ 这就是「忘了 % m」的症状：egcd 给的系数是负数。")
            print("      注意 a·d % m 仍然等于 1，Bézout 也仍然成立 ——")
            print("      【二】那一组检查抓不住它，只有这一条能。")

    # ---- 负向检查二：逆元不存在时必须报错 ----
    print()
    print("【四】⚠ 逆元不存在时必须抛 ValueError，而不是返回一个错值")
    missing = [(4, 12), (6, 9), (100, 250), (2, 4)]
    wrong = []
    for a, m in missing:
        try:
            d = modinv(a, m)
        except ValueError:
            continue                     # 正确行为
        wrong.append((a, m, d))
    if wrong:
        ok = False
        for a, m, d in wrong:
            print(f"  ✗ modinv({a}, {m}) 返回了 {d}，"
                  f"但 gcd({a}, {m}) = {_math_gcd(a, m)} ≠ 1，逆元根本不存在")
        print("    检查一下 modinv 里有没有「g != 1 就 raise ValueError」这一句"
              "（填空 6）。")
    else:
        print(f"  全部 {len(missing)} 例都正确抛出了 ValueError")

    # ---- 【五】φ(n) 的两种情形：本任务后果最重的一处 ----
    #
    # 【为什么这一块必须存在，而且必须用「手算得来」的值当预言机】
    # φ 原本是随包给的（rsa_common.totient），构造上保证正确。搬进任务一
    # 之后，它变成了**可能写错的东西**，而写错的后果不在这个文件里 ——
    # 它要等到 60 分钟之后、任务四解那份 PDF 时才发作。
    #
    # 所以这里用一个**独立预言机**：下面几个期望值是手算出来的
    # （不是用同一个公式算的，否则错法会被原样复制一遍）：
    #
    #     φ(61, 53) = 60 × 52 = 3120          ← 普通情形，两位素数好算
    #     φ(7, 7)   = 42                      ← p² = 49，与 49 互素的数
    #                                           有 1..48 里除去 7 的倍数，
    #                                           48 − 6 = 42
    #     反过来验 (7−1)² = 36 ≠ 42          ← 这是抓 (p−1)² 的那一条
    #
    # 两条都要查：只查普通情形抓不住 p = q 写错，只查 p = q 抓不住
    # 把两个分支写反（见 totient 文档串最后一段）。
    print()
    print("【五】⚠ φ(n) 的两种情形 —— 错了要到任务四才发作")
    phi_cases = [
        ((61, 53), 3120, "普通情形 p ≠ q"),
        ((7, 7), 42, "完全平方 p²（不是 (7−1)²=36）"),
        ((11, 11), 110, "再来一个平方，防巧合"),
    ]
    phi_bad = []
    for (p, q), want, why in phi_cases:
        got = totient(p, q)
        if got != want:
            phi_bad.append((p, q, got, want, why))
    if phi_bad:
        ok = False
        for p, q, got, want, why in phi_bad:
            print(f"  ✗ totient({p}, {q}) = {got}，应当是 {want}   （{why}）")
        print()
        print("    最常见的错法：只写了 (p−1)(q−1) 一条公式。它在 p ≠ q 时")
        print("    完全正确，在 p = q 时算出 (p−1)² —— 比真值 p(p−1) 少了 p−1。")
        print("    检查填空 8/9/10：分支条件和两条 return 是不是配套的。")
    else:
        print(f"  全部 {len(phi_cases)} 例通过（含 (p−1)² = 36 ≠ 42 的反例）")

    # ---- 收尾：三问 ----
    print()
    print(DASH)
    print("自检通过后，顺手想清楚这三问：")
    print("  (a) 为什么 gcd(a, m) ≠ 1 时逆元不存在？")
    print("  (b) Bézout 恒等式成立，为什么还不足以说明 d 是「合格」的逆元？")
    print("  (c) φ(p²) 算错成 (p−1)² 时，程序一声不吭。为什么「d 落在")
    print("      [0, φ) 内」这条检查抓不住它？")
    print()
    print("  (c) 就是报告里任务一那一问，现在就可以先想；")
    print("  (a)(b) 想清楚了对我们理解RSA算法很有帮助。")
    print(DASH)

    return ok


def main() -> None:
    ap = argparse.ArgumentParser(description="任务一：扩展欧几里得 + 模逆 + φ")
    ap.add_argument("--selftest", action="store_true",
                    help="跑自检（填完 10 个空就跑这个）")
    args = ap.parse_args()

    if not args.selftest:
        ap.print_help()
        print()
        print("加 --selftest 跑自检。")
        return

    ok = _self_test()
    print()
    if ok:
        print("全部通过 —— 任务一完成，可以带着它上任务二了。")
    else:
        print("存在失败项。对照上面的提示改，或看《学生上机步骤》")
        print("「卡住了怎么办」表里任务一那一行。")
        raise SystemExit(1)


if __name__ == "__main__":
    run(main)
