def modinv(a: int, m: int) -> int:
    """求 a 在模 m 下的乘法逆元，即满足 a·d ≡ 1 (mod m) 的 d。

    实现很短：调用你刚写好的 egcd，从返回值里取出系数，
    再把它**归约到 [0, m) 区间**。三行以内。

    【两个必须做对的地方】

    1. **gcd(a, m) 必须等于 1，否则逆元根本不存在**，此时应当抛
       ValueError。在 RSA 里这条就是「e 必须与 φ(n) 互素」——
       它是 RSA 能成立的前提之一。不检查的话，你会拿到一个看起来
       正常的数，而它根本不是逆元。

    2. **返回值必须落在 [0, m) 区间内。**
       egcd 给出的系数是**可能为负**的。比如 a=3、m=7：

           egcd(3, 7)  ->  (1, -2, 1)      因为 3×(−2) + 7×1 = 1

       x = −2 是完全合法的 Bézout 系数，但它不是「逆元」的规范形式。
       归约一下就对了：−2 mod 7 = 5，验算 3×5 = 15 ≡ 1 (mod 7) ✓。

    【⚠ 为什么第 2 点必须做，而不是「顺手做做」】
    因为你**不会**因此在自检里报错：

      · Bézout 恒等式对 x = −2 照样成立（它本来就是解）；
      · 在 Python 里 `e * d % phi == 1` 对 d = −2 也**照样为真** ——
        因为 Python 的 % 总是返回非负数。

    于是你会揣着一个负的 d 一路走到任务四，直到解密失败才发现问题，
    而且完全不知道问题出在几百行之前的这里。
    所以下面的自检专门加了「0 ≤ d < m」这一条 —— 那是唯一能抓住它的检查。
    """
    # TODO(5): 调用 egcd，一次取出三个返回值。
    #          提示：g, x, _ = ？        （第三个返回值我们不用，习惯上叫 _）
    g, x, _ = egcd(a, m)

    # TODO(6): 逆元不存在时必须抛 ValueError，而不是往下走。
    #          提示：这是一个条件表达式 —— g 不等于 1
    if g != 1:
        raise ValueError(f"{a} 在模 {m} 下没有逆元：gcd({a}, {m}) = {g} ≠ 1")

    # TODO(7): 把 x 归约到 [0, m) 区间再返回。
    return x % m


# ---------------------------------------------------------------------------
# 填空 8、9、10：φ(n) —— d 的分母
# ---------------------------------------------------------------------------
#
# 【为什么这个函数现在归你写】
# 在 rsa-lab3 里，totient() 是随包附带的（在 rsa_common.py 里），
# 你只需要调用它。但那让「φ(p²) 该写成什么」变成了一个**别人替你
# 保证正确**的细节，而你恰恰是这个细节的受益者兼受害者：
#
#     · 共享素因子那 5 台：p ≠ q，用 (p−1)(q−1)
#     · 完全平方那 1 台：p = q，φ(p²) = p(p−1)，**不是** (p−1)²
#
# 后者是全包后果最重的陷阱。所以它现在归你写 —— 你会写错一次，
# 然后在下面【五】那个检查上花五秒钟改对，而不是在 60 分钟之后的
# 任务四上对着一份解不开的 PDF 发呆。


def totient(p: int, q: int) -> int:
    """由两个素因子算欧拉函数 φ(n)。**两种情形要分开**。

        p ≠ q   φ(n) = (p − 1)(q − 1)
        p = q   φ(p²) = p² − p = p(p − 1)      ← 不是 (p − 1)²

    【为什么第二种情形容易写错，而且写错了不报错】
    三个函数加起来三条公式，只有这一条有两个分支。绝大多数人会顺手写成

        return (p - 1) * (q - 1)

    这在 p ≠ q 时完全正确，在 p = q 时算出 (p−1)²，比真值 p(p−1)
    **少了 p−1** —— 差一个 512 位的数。

    后果：d = e⁻¹ mod φ 算出来是一个**合法范围内的错值**。它不会越界、
    不会抛异常、不会让程序变慢，`e·d ≡ 1` 也照样成立（模的是错的那个
    φ）。唯一的症状是 60 分钟之后任务四解不开那份 PDF。

    ⚠ 特别注意：**「d 落在 [0, φ) 内」这个检查抓不住它。**
    因为 φ_wrong = (p−1)² < p(p−1) = φ_true，算出来的 d 本来就更小，
    照样落在范围里。真正能抓住它的是**往返验证**（加密回去看看对不对），
    以及这个文件自检里的【五】。

    【怎么手算验证】
    p = 3、n = 9 时，与 9 互素的数是 1,2,4,5,7,8 共 6 个；
    p(p−1) = 3 × 2 = 6 ✓，而 (p−1)² = 4 ✗。

    【填空 8 写反了会怎样】
    两种写法都有人用（`if p != q` 或 `if p == q`），但**必须和两条
    return 配套**。写反了的话两个分支会各错一半 —— 比如拦下 p ≠ q
    却返回 p(p−1)，那颗 61、53 的普通用例会当场算出 3660 而不是 3120，
    【五】立刻报。所以这一处**错了会响**，不用担心它悄悄溜过去。
    """
    # TODO(8): 判断该走哪个分支 —— 这一句拦下的是**普通**情形。
    #          提示：两个素因子不相等，就用 (p−1)(q−1) 那条公式。
    #          这是一个条件表达式，把它填进 if 里。
    if p != q:
        # TODO(9): 普通情形。这就是那个「顺手写」的公式。
        return (p - 1) * (q - 1)

    # TODO(10): 两个素因子**相等**才会走到这里（完全平方模数 n = p²）。
    #           φ(p²) = p² − p，化简一下是 p(p−1)。别写成 (p−1)²。
    return p * (p - 1)


