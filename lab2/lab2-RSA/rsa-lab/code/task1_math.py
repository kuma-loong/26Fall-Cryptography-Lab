def egcd(a: int, b: int) -> tuple[int, int, int]:
    """扩展欧几里得算法：返回 (g, x, y)，满足 a·x + b·y = g = gcd(a, b)。

    这个恒等式叫 **Bézout 恒等式**（裴蜀等式）。它为什么有用：
    当 g = 1 时，两边对 a 取模，第一项 a·x 就没了，得到

        b·y ≡ 1  (mod a)

    也就是 y 恰好是 b 在模 a 下的乘法逆元。**模逆是免费送的** ——
    这正是扩展欧几里得比普通欧几里得值钱的地方。

    下面是标准的**迭代版**（不递归，免得在大数上爆栈）。
    (old_r, r) 是「上一个余数」和「当前余数」，(old_s, s)、(old_t, t)
    是 x、y 两个系数在同样几步上的取值。循环结束的条件是 r == 0，
    此时 old_r 就是 gcd，old_s、old_t 就是 x、y。

    【填空 3 和填空 4】
    循环体里还有两行「同时更新」。以已经写好的第一行为例，
    数学上是

        (old_r, r) = (r, old_r - q * r)

    Python 里就要写成元组赋值：

        old_r, r = r, old_r - q * r          ← 对

    ⚠ **不能**拆成两句：

        old_r = r                             ← 错！
        r = old_r - q * r

    第二句里的 old_r 已经被第一句覆盖成 r 了，实际算的是 r − q·r。
    这是本任务最高频的错误：**程序不报错，只是答案全错**。

    你要填的两行，结构和第一行完全一样：把 old_r/r 换成 old_s/s，
    再把 q * r 换成 q * s。

    【填空 1 和填空 2：那两行初始化】
    循环开始**之前**，(old_s, s)、(old_t, t) 必须先有正确的初值，
    否则循环体算得再对也没用。

    初值来自「把 a、b 自己写成自己的线性组合」这个平凡等式：

        a = 1·a + 0·b        →  a 的系数是 (1, 0)
        b = 0·a + 1·b        →  b 的系数是 (0, 1)

    对照上面 (old_r, r) = (a, b) 的写法，你就知道那两行该长什么样了。
    ⚠ 别把这两行填到循环体**里面**去 —— 那会在每一轮把系数重置回初值，
    循环跑完拿到的永远是 (1, 0)，Bézout 检查会立刻抓到。
    """
    old_r, r = a, b

    # TODO(1): 给 (old_s, s) 一个正确的初值。这一整行都要你自己写。
    #          提示：a = 1·a + 0·b，所以 s 那一对是 ？
    old_s, s = 1, 0

    # TODO(2): 给 (old_t, t) 一个正确的初值。同理。
    #          提示：b = 0·a + 1·b
    old_t, t = 0, 1

    while r:
        q = old_r // r
        old_r, r = r, old_r - q * r

        # TODO(3): 同时更新 (old_s, s)。这一整行都要你自己写，
        #          把 FILL[3] 删掉，在原位写上你的语句。
        #          提示：old_s, s = ？
        old_s, s = s, old_s - q * s

        # TODO(4): 同时更新 (old_t, t)。同理。
        old_t, t = t, old_t - q * t

    return old_r, old_s, old_t


